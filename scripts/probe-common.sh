#!/usr/bin/env bash
# probe-common.sh —— Phase 3 四个证据探针（03-01 probe-lock / 03-02 probe-fullscreen /
# 03-03 probe-display / 03-04 probe-power）共用的那一块。**本文件只有一个函数：alarm()。**
#
# 为什么只有它：19 个脚本都有 `alarm()`，但这四个是**整块逐字相同**、且只有这四个
# 被 test.sh 的 Phase 3 段真跑（test.sh:335-338）。改这四个有自动验证兜底，另外 15 个
# 改了没人跑 —— 那 15 个留在原地，等它们各自接进门禁再收（TODO）。
#
# `cleanup()` 与 `trap` **刻意不收进来**：四个脚本的清理逻辑各不相同（临时目录、driver
# 进程、evidence 落点都不一样），收进公共文件会把差异藏起来。各脚本原地保留。
#
# 纪律（四个脚本头注释里逐字重复的那条）：本机没有 timeout 命令，所有外部命令套
# `alarm N 命令 …` —— 权限弹窗或异常输入会挂死采集（Phase 1 已踩过）。

# ⚠️ 调用约定：`alarm()` 按位置参数取参 —— `$1` 取调用方当前位置参数（秒数），
#    `${@:2}` 取待 exec 的命令。所以**调用方脚本勿用位置参数**：不要指望把脚本级
#    的 `$1`/`$2` 顺带传进来，秒数与命令必须逐字写在 `alarm` 的实参里。
alarm() { perl -e "alarm $1; exec @ARGV" "${@:2}"; }
